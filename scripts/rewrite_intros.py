def rewrite_intro(file_path):
    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Get Chapter number
    chapter_match = re.search(r'chapter-(\d+)\.html', os.path.basename(file_path))
    if not chapter_match: return False
    chap_num = int(chapter_match.group(1))

    if chap_num not in intros:
        return False

    intro_p = intros[chap_num]

    # Find the title (h2)
    # The structure usually has <article class="container"><div class="article-content">
    # <h2>Title</h2><p>Original Intro...</p>
    # We will search for the first <p> after <div class="article-content"> and replace it, but maybe safer to find the first <p> after <h2>
    
    # regex sub: replace the first <p>...</p> after the first <h2>
    # Note: re.sub with count=1 or a specialized function.
    
    def replace_first_p(match):
        header = match.group(0)
        # Search the text inside the matched part for the first <p> and </p>
        return re.sub(r'<p>.*?</p>', intro_p, header, count=1, flags=re.DOTALL)
    
    # We find the span from <div class="article-content"> to the first <h2> and the following <p>
    content, count = re.subn(r'(<div class="article-content">[\s\S]*?<h2>[\s\S]*?</h2>[\s\S]*?)<p>.*?</p>', r'\1' + intro_p, content, count=1)

    if count > 0:
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)
        return True
    return False

